#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
APP_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/applications"
BIN_DIR="$HOME/.local/bin"

mkdir -p "$APP_DIR" "$BIN_DIR"
ln -sfn "$ROOT/droidrun" "$BIN_DIR/droidrun"
# Preserve the previous CLI shortcut for existing users.
ln -sfn "$ROOT/droidrun" "$BIN_DIR/android-build-install"

write_desktop_entry() {
    local entry_root="$1" command_name="$2"
    cat <<EOF
[Desktop Entry]
Type=Application
Name=DroidRun
Icon=$entry_root/android_build_install_linux/assets/droidrun-icon.png
Comment=Build, sync, install, and launch Android projects
Exec="$BIN_DIR/$command_name" %f
Terminal=false
Categories=Development;
StartupNotify=true
EOF
}

write_desktop_entry "$ROOT" droidrun > "$APP_DIR/droidrun.desktop"

chmod 0644 "$APP_DIR/droidrun.desktop"
# Clean up only an unchanged entry generated by this checkout, after success.
# Do not follow symlinks or remove launchers customized/owned by someone else.
legacy_entry="$APP_DIR/android-build-install.desktop"
old_root="$(dirname -- "$ROOT")/android-build-install-linux"
if [[ -f "$legacy_entry" && ! -L "$legacy_entry" ]]; then
    for entry_root in "$ROOT" "$old_root"; do
        if cmp -s -- "$legacy_entry" <(write_desktop_entry "$entry_root" android-build-install); then
            rm -- "$legacy_entry"
            break
        fi
    done
fi
command -v update-desktop-database >/dev/null 2>&1 && update-desktop-database "$APP_DIR" || true
printf 'Installed %s\n' "$APP_DIR/droidrun.desktop"
